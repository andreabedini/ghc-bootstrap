#!/usr/bin/env python3
"""Emit build/mk/deps.mk: the per-module rules of build/Makefile with the real
import graph, for libraries/base (build/ghc622-mhs/diag/base-rebuild-order.txt),
libraries/haskell98 and the compiler proper (build/ghc622-stage2/order.txt),
the last twice: stage 2 (compiled by the mhs-built stage 1 into stage2/) and
stages 3 and 4 (each compiled by the previous stage's native compiler into
stage<n>/ and obj-stage<n>/, linked as ghc-stage<n>) and stage 5 (compiled by
ghc-stage4 into stage5/, interfaces and Abstract C only).

Edges come from the same scanners the order files came from: base-order.py's
cpp'd import scan for base, phase2/build-order.py's scan (plus the HsVersions.h
`import qualified FastString` edge of make-order.py) for the compiler. SOURCE
imports are not edges. Only edges inside each package are emitted; a stage-2
module depends on the libraries through $(LIBS_STAMP). The compile scripts and
flags.tsv are order-only prerequisites: editing a recipe's retry ladder or its
logging must not schedule a five-hour rebuild.

    python3 build/mk/gen-deps.py > build/mk/deps.mk      (needs GHC_BOOTSTRAP_ROOT)
"""
import importlib.util, os, re, subprocess, sys

R = os.environ["GHC_BOOTSTRAP_ROOT"]
M1 = R + "/build/ghc622-mhs"; S2 = R + "/build/ghc622-stage2"
BASE = M1 + "/libraries/base"; H98 = S2 + "/libraries/haskell98"
SRC2 = S2 + "/src/ghc-6.2.2/ghc/compiler"; INC1 = R + "/build/ghc-6.2.2-run1/ghc/includes"

out = []
def emit(s=""): out.append(s)

# ---------------------------------------------------------------- base
def base_deps(mods):
    """module -> intra-package imports, after cpp (as base-order.py)."""
    cpp = ["gcc", "-E", "-undef", "-traditional", "-x", "c", "-P",
           "-D__HASKELL1__=5", "-D__GLASGOW_HASKELL__=602", "-D__HASKELL98__",
           "-D__CONCURRENT_HASKELL__", "-I" + BASE + "/include", "-I" + INC1, "-"]
    imp = re.compile(r'^\s*(?:>\s*)?import\s+(?:qualified\s+)?([A-Z][\w.]*)', re.M)
    srcimp = re.compile(r'^\s*(?:>\s*)?import\s+\{-#\s*SOURCE\s*#-\}', re.M)
    deps = {}
    for m, f in mods.items():
        raw = open(f, encoding="latin-1").read()
        if f.endswith(".lhs"):
            if "\\begin{code}" in raw:
                keep, ls = False, []
                for l in raw.splitlines():
                    if l.startswith("\\begin{code}"): keep = True; ls.append(""); continue
                    if l.startswith("\\end{code}"): keep = False; ls.append(""); continue
                    ls.append(l if keep else "")
                raw = "\n".join(ls)
            else:
                raw = "\n".join(l[1:] if l.startswith(">") else "" for l in raw.splitlines())
        txt = subprocess.run(cpp, input=raw.encode("latin-1"), capture_output=True).stdout.decode("latin-1")
        ds = set()
        if "-fno-implicit-prelude" not in raw and m != "Prelude" and "Prelude" in mods:
            ds.add("Prelude")
        for line in txt.splitlines():
            if srcimp.match(line): continue
            mm = imp.match(line)
            if mm and mm.group(1) in mods and mm.group(1) != m:
                ds.add(mm.group(1))
        deps[m] = ds
    return deps

base_order = [l.strip() for l in open(M1 + "/diag/base-rebuild-order.txt") if l.strip()]
base_mods = {}
for m in base_order:
    p = m.replace(".", "/")
    for ext in (".lhs", ".hs"):
        if os.path.exists(BASE + "/" + p + ext):
            base_mods[m] = BASE + "/" + p + ext; break
    else:
        sys.exit("base: no source for " + m)
bdeps = base_deps(base_mods)

emit("# Generated by build/mk/gen-deps.py -- do not edit.")
emit("BASE_MODS := " + " ".join(base_order))
emit("BASE_HIS := " + " ".join("$(BASE)/%s.hi" % m.replace(".", "/") for m in base_order))
emit("BASE_OBJS := " + " ".join("$(M1)/hcobj/%s.o" % m.replace(".", "_") for m in base_order))
emit()
for m in base_order:
    p = m.replace(".", "/"); src = base_mods[m][len(BASE) + 1:]
    ds = " ".join("$(BASE)/%s.hi" % d.replace(".", "/") for d in sorted(bdeps[m]))
    emit("$(BASE)/%s.hi $(BASE)/%s.hc &: $(BASE)/%s %s $(BASE_HDRS) $(M1)/ghc | $(MK)/compile-base.sh" % (p, p, src, ds))
    emit("\tsh $(MK)/compile-base.sh %s" % m)
    emit("$(M1)/hcobj/%s.o: $(BASE)/%s.hc" % (m.replace(".", "_"), p))
    emit("\t$(HC2O_BASE)")
emit()

# ---------------------------------------------------------------- haskell98
h98_mods = sorted(f[:-3] for f in os.listdir(H98) if f.endswith(".hs"))
imp98 = re.compile(r'^\s*import\s+(?:qualified\s+)?([A-Z][\w.]*)', re.M)
emit("H98_MODS := " + " ".join(h98_mods))
emit("H98_HIS := " + " ".join("$(H98)/%s.hi" % m for m in h98_mods))
emit("H98_OBJS := " + " ".join("$(H98)/obj/%s.o" % m for m in h98_mods))
emit()
for m in h98_mods:
    ds = sorted(d for d in imp98.findall(open(H98 + "/" + m + ".hs", encoding="latin-1").read()) if d in h98_mods and d != m)
    dstr = " ".join("$(H98)/%s.hi" % d for d in ds)
    emit("$(H98)/%s.hi $(H98)/%s.hc &: $(H98)/%s.hs %s $(BASE_HIS) $(M1)/lib/libHSbase.a $(M1)/ghc | $(MK)/compile-h98.sh" % (m, m, m, dstr))
    emit("\tsh $(MK)/compile-h98.sh %s" % m)
    emit("$(H98)/obj/%s.o: $(H98)/%s.hc" % (m, m))
    emit("\t$(HC2O_H98)")
emit()

# ---------------------------------------------------------------- stage 2
spec = importlib.util.spec_from_file_location("bo", R + "/phase2/build-order.py")
bo = importlib.util.module_from_spec(spec); spec.loader.exec_module(bo)
deps2, defined = bo.scan(SRC2, skip_dirs=("nativeGen", "ilxGen", "javaGen", "ghci"))
order2 = []
for l in open(S2 + "/order.txt"):
    if l.strip():
        m, p = l.rstrip("\n").split("\t"); order2.append((m, p))
mods2 = {m for m, _ in order2}
for m, p in order2:
    src = open(SRC2 + "/" + p, encoding="latin-1").read()
    if m != "FastString" and 'include "HsVersions.h"' in src and "define COMPILING_FAST_STRING" not in src:
        deps2.setdefault(m, set()).add("FastString")
def obj2(p):
    return os.path.splitext(p)[0].replace("/", "_")
emit("STAGE2_MODS := " + " ".join(m for m, _ in order2))
emit("STAGE2_HIS := " + " ".join("$(ODIR2)/%s.hi" % os.path.splitext(p)[0] for _, p in order2))
emit("STAGE2_OBJS := " + " ".join("$(S2)/obj/%s.o" % obj2(p) for _, p in order2))
# stages 3..5: each compiled by the previous stage's native compiler; 3 and 4
# are linked (objects), 5 is interfaces and Abstract C only (compare5).
STAGES = {3: ("$(S2)/ghc", True), 4: ("$(S2)/ghc-stage3", True), 5: ("$(S2)/ghc-stage4", False)}
for n, (ghc, objs) in STAGES.items():
    emit("STAGE%d_HIS := " % n + " ".join("$(ODIR%d)/%s.hi" % (n, os.path.splitext(p)[0]) for _, p in order2))
    if objs:
        emit("STAGE%d_OBJS := " % n + " ".join("$(S2)/obj-stage%d/%s.o" % (n, obj2(p)) for _, p in order2))
emit()
path_of = dict(order2)
for m, p in order2:
    stem = os.path.splitext(p)[0]
    ds = [os.path.splitext(path_of[d])[0] + ".hi" for d in sorted(deps2.get(m, ())) if d in mods2 and d != m]
    fix = " $(S2)/fixups/%s" % p if os.path.exists(S2 + "/fixups/" + p) else ""
    # stage 2: the stage-1 (mhs-built) compiler, fixups for what the MicroHs runtime cannot read
    emit("$(ODIR2)/%s.hi $(ODIR2)/%s.hc &: $(SRC2)/%s%s %s $(LIBS_STAMP) $(M1)/ghc | $(S2)/flags.tsv $(MK)/compile-stage2.sh" % (stem, stem, p, fix, " ".join("$(ODIR2)/" + d for d in ds)))
    emit("\tsh $(MK)/compile-stage2.sh %s %s" % (m, p))
    emit("$(S2)/obj/%s.o: $(ODIR2)/%s.hc" % (obj2(p), stem))
    emit("\t$(HC2O_STAGE2)")
    # stages 3..5: a native compiler on the pristine source, no fixups, no seeded flags
    for n, (ghc, objs) in STAGES.items():
        emit("$(ODIR%d)/%s.hi $(ODIR%d)/%s.hc &: $(SRC2)/%s %s $(LIBS_STAMP) %s | $(MK)/compile-stage2.sh" % (n, stem, n, stem, p, " ".join("$(ODIR%d)/" % n + d for d in ds), ghc))
        emit("\t$(STAGE%d_ENV) sh $(MK)/compile-stage2.sh %s %s" % (n, m, p))
        if objs:
            emit("$(S2)/obj-stage%d/%s.o: $(ODIR%d)/%s.hc" % (n, obj2(p), n, stem))
            emit("\t$(HC2O_STAGE2)")
print("\n".join(out))
print("# %d base, %d haskell98, %d stage-2 modules" % (len(base_order), len(h98_mods), len(order2)), file=sys.stderr)
